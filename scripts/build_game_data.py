"""Build the game data from cards.json.

Writes:
  supabase/migrations/20261022000002_cards.sql  playable cards for the database (upsert, safe to re-run)
  names.json                                    names for the guess box's suggestions (no card ids, no images)

Playable = series in ERAS, and not a full art (by rarity) nor a Pokémon V / VMAX / VSTAR / ex (by name),
the same rule as the game. Run from the repository root:  python3 scripts/build_game_data.py
"""
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ERAS = {"me", "swsh", "sv"}
FULL_ART = re.compile(
    r"^(ultra rare|secret rare|illustration rare|special illustration rare|hyper rare|mega hyper rare|"
    r"shiny ultra rare|black white rare|mega attack rare|rgb rare|futuristic rare|holo rare v|holo rare vmax|"
    r"holo rare vstar|double rare)$", re.I)
FULL_ART_NAME = re.compile(r" (ex|V|VMAX|VSTAR)$")


def q(s):
    return "null" if s is None else "'" + str(s).replace("'", "''") + "'"


def main(out_sql=None):
    db = json.loads((ROOT / "cards.json").read_text(encoding="utf-8"))
    base = db.get("imageBase", "https://assets.tcgdex.net/en")
    rows, names = [], set()
    for c in db["cards"]:
        st = db["sets"][c[0]]
        serie = db["series"][st[2]][0]
        if serie not in ERAS:
            continue
        rarity = db["rarities"][c[3]] if c[3] is not None and c[3] < len(db["rarities"]) else None
        name = c[2]
        if (rarity and FULL_ART.match(rarity)) or FULL_ART_NAME.search(name):
            continue
        cid = f"{st[0]}-{c[1]}"
        rows.append(f"({q(cid)},{q(serie)},{q(st[0])},{q(st[1])},{q(c[1])},{q(name)},{q(rarity)},"
                    f"{'true' if c[4] else 'false'},{q(base + '/' + serie + '/' + st[0] + '/' + c[1])})")
        names.add(name)

    sql = ["-- Playable cards, generated by scripts/build_game_data.py from cards.json. Do not edit by hand.",
           f"-- {len(rows)} cards, data of {db.get('generated', '?')}."]
    for i in range(0, len(rows), 500):
        sql.append("insert into public.cards (id, serie, set_id, set_name, number, name, rarity, has_evo, image) values\n"
                   + ",\n".join(rows[i:i + 500])
                   + "\non conflict (id) do update set serie = excluded.serie, set_id = excluded.set_id, "
                     "set_name = excluded.set_name, number = excluded.number, name = excluded.name, "
                     "rarity = excluded.rarity, has_evo = excluded.has_evo, image = excluded.image;")
    out = Path(out_sql) if out_sql else ROOT / "supabase/migrations/20261022000002_cards.sql"
    out.write_text("\n\n".join(sql) + "\n", encoding="utf-8")
    (ROOT / "names.json").write_text(json.dumps(sorted(names), ensure_ascii=False, separators=(",", ":")),
                                          encoding="utf-8")
    print(f"{len(rows)} playable cards, {len(names)} names")


if __name__ == "__main__":
    import sys
    main(sys.argv[1] if len(sys.argv) > 1 else None)
